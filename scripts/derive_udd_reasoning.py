#!/usr/bin/env python
"""Derive verified rationales + diversified instruction/answer variants over the UDD corpus.

    # read UDD from the Hub WITHOUT the image column (column projection over HTTP), then run
    python scripts/derive_udd_reasoning.py --from-hub
    # or from a local no-image dump / parquet
    python scripts/derive_udd_reasoning.py --rows rows.json
    python scripts/derive_udd_reasoning.py --rows data/train-00000-of-00005.parquet --sources cord funsd

Writes
  examples/udd_reasoning/rows.jsonl       augmented rows (reasoning, repaired answers, derived QAs,
                                           reasoning_provenance, evidence_box) — git-ignored
  examples/udd_reasoning/variants.jsonl   one record per (instruction, answer) variant — git-ignored
  docs/results/udd_reasoning_stats.json   per-source yield, gate rejections, diversity before/after
  docs/results/udd_reasoning_preview.md   human-readable examples per source

See docs/report/benchmark_reasoning_extraction.md.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from docvlm_eval.unified.diversify import (
    DEFAULT_CONFIG,
    DiversityConfig,
    diversify_row,
    diversity_stats,
)
from docvlm_eval.unified.rationale import attach

COLS = ["sample_id", "source", "task", "instructions", "answers", "answer_variants", "reasoning",
        "task_detail", "qa_tasks", "elements_json", "full_annotation", "image_width",
        "image_height", "language", "fold", "metric"]
HUB_FILES = [f"datasets/danelcsb/UDD/data/train-0000{i}-of-00005.parquet" for i in range(5)]


def load_rows(args) -> list[dict]:
    import pyarrow.parquet as pq
    if args.from_hub:
        from huggingface_hub import HfFileSystem
        fs = HfFileSystem()
        rows = []
        for p in HUB_FILES:
            with fs.open(p, "rb", block_size=8 * 2**20) as f:
                pf = pq.ParquetFile(f)
                cols = [c for c in COLS if c in pf.schema_arrow.names]
                rows += pf.read(columns=cols).to_pylist()
            print(f"[hub] {p}: {len(rows)} rows so far")
        return rows
    p = Path(args.rows)
    if p.suffix == ".parquet":
        pf = pq.ParquetFile(p)
        return pf.read(columns=[c for c in COLS if c in pf.schema_arrow.names]).to_pylist()
    if p.suffix == ".jsonl":
        return [json.loads(x) for x in p.read_text(encoding="utf-8").splitlines() if x.strip()]
    return json.loads(p.read_text(encoding="utf-8"))


def _pairs(rows: list[dict]) -> list[tuple[str, str, list[str]]]:
    return [(q, "original", [a]) for r in rows for q, a in zip(r["instructions"], r["answers"])]


def _preview(by_src: dict[str, list[dict]], variants: dict[str, list], per_source: int = 2) -> str:
    lines = ["# UDD reasoning + instruction diversity — preview",
             "",
             ("Generated by `scripts/derive_udd_reasoning.py` "
              "(design: [`../report/benchmark_reasoning_extraction.md`](../report/benchmark_reasoning_extraction.md))."),
             ("Each block shows one QA that received a rationale: the instruction, the gold, the rationale "
              "with its provenance tier, and the diversified (instruction, answer) variants drawn for it."),
             ""]
    for src in sorted(by_src):
        shown = 0
        for r in by_src[src]:
            for i, prov in enumerate(r["reasoning_provenance"]):
                if not prov or prov == "repaired" or prov.startswith("rejected:") or shown >= per_source:
                    continue
                shown += 1
                if shown == 1:
                    lines += [f"## {src}", ""]
                q = r["instructions"][i].replace("\n", " ⏎ ")
                if len(q) > 300:
                    q = "…" + q[-300:]
                lines += [f"**Q** ({r['sample_id']}, QA {i}{', derived' if (r.get('task_detail') or [''] * (i + 1))[i].startswith('derived:') else ''}): {q}",
                          "",
                          f"**Gold:** `{r['answers'][i][:200]}`",
                          "",
                          f"**Rationale** — `{prov}`: {r['reasoning'][i]}",
                          ""]
                vs = [v for v in variants.get(r["sample_id"], []) if v.meta.get("qa_index") == i
                      and v.format != "original"]
                if vs:
                    lines += ["| format | instruction | target |", "| --- | --- | --- |"]
                    for v in vs:
                        ins = v.instruction.replace("\n", " ⏎ ").replace("|", "\\|")
                        if len(ins) > 160:
                            ins = "…" + ins[-160:]
                        tgt = v.answers[0].replace("\n", " ⏎ ").replace("|", "\\|")[:220]
                        lines.append(f"| {v.format} | {ins} | {tgt} |")
                    lines.append("")
            if shown >= per_source:
                break
    lines += ["## Answer-only sources (no verifiable rationale) — instruction/answer variants only", "",
              ("These sources ship no derivation, evidence or structure in UDD, so no rationale is "
               "attached; they still get format-bound instruction/answer variants."), "",
              "| source | original instruction → gold | format | variant instruction | target |",
              "| --- | --- | --- | --- | --- |"]
    for src in sorted(by_src):
        r = next((x for x in by_src[src] if not any(p and not p.startswith("rejected:")
                                                    for p in x["reasoning_provenance"])), None)
        if r is None:
            continue
        vs = [v for v in variants.get(r["sample_id"], []) if v.meta.get("qa_index") == 0 and v.format != "original"]

        def cell(t, n=110):
            t = t.replace("\n", " ⏎ ").replace("|", "\\|")
            return t if len(t) <= n else "…" + t[-n:]
        for k, v in enumerate(vs):
            orig = f"{cell(r['instructions'][0])} → `{cell(r['answers'][0], 60)}`" if k == 0 else ""
            lines.append(f"| {src if k == 0 else ''} | {orig} | {v.format} | {cell(v.instruction)} | {cell(v.answers[0], 80)} |")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    src = ap.add_mutually_exclusive_group(required=True)
    src.add_argument("--from-hub", action="store_true")
    src.add_argument("--rows", help="local .json / .jsonl / .parquet of UDD rows")
    ap.add_argument("--sources", nargs="*", help="only these sources")
    ap.add_argument("--config", default=str(DEFAULT_CONFIG))
    ap.add_argument("--out", default=str(ROOT / "examples" / "udd_reasoning"))
    ap.add_argument("--stats", default=str(ROOT / "docs" / "results" / "udd_reasoning_stats.json"))
    ap.add_argument("--preview", default=str(ROOT / "docs" / "results" / "udd_reasoning_preview.md"))
    args = ap.parse_args(argv)

    rows = load_rows(args)
    if args.sources:
        rows = [r for r in rows if r["source"] in set(args.sources)]
    cfg = DiversityConfig.from_yaml(args.config)
    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)

    per = defaultdict(lambda: Counter())
    rejected = defaultdict(Counter)
    tiers = defaultdict(Counter)
    aug_rows, by_src, var_by_id = [], defaultdict(list), {}
    all_vars = []
    with (out_dir / "rows.jsonl").open("w", encoding="utf-8") as fr, \
         (out_dir / "variants.jsonl").open("w", encoding="utf-8") as fv:
        for r in rows:
            nr, rep = attach(r)
            s = r["source"]
            c = per[s]
            c["rows"] += 1
            c["qas_before"] += len(r["instructions"])
            c["qas_after"] += len(nr["instructions"])
            c["reasoning_before"] += sum(1 for x in (r.get("reasoning") or []) if (x or "").strip())
            c["reasoning_after"] += sum(1 for x in nr["reasoning"] if (x or "").strip())
            c["answers_repaired"] += sum(1 for a, b in zip(r["answers"], nr["answers"]) if a != b)
            c["derived_qas"] += len(nr["instructions"]) - len(r["instructions"])
            for d, w in rep["rejected"]:
                rejected[s][f"{d}:{w}"] += 1
            for d, t, _ in rep["kept"]:
                tiers[s][t] += 1
            vs = diversify_row(nr, cfg)
            c["variants"] += len(vs)
            var_by_id[nr["sample_id"]] = vs
            all_vars += vs
            by_src[s].append(nr)
            slim = {k: v for k, v in nr.items() if k not in ("elements_json", "full_annotation")}
            fr.write(json.dumps(slim, ensure_ascii=False) + "\n")
            for v in vs:
                fv.write(json.dumps({"sample_id": v.sample_id, "udd_sample_id": nr["sample_id"],
                                     "question": v.instruction, "answers": v.answers,
                                     "answer_type": nr.get("task"), "metric": v.metric,
                                     "meta": {**v.meta, "format": v.format, "final_answers": v.final_answers,
                                              "fold": nr.get("fold"),
                                              "reasoning_provenance": nr["reasoning_provenance"][v.meta["qa_index"]]}},
                                    ensure_ascii=False) + "\n")
            aug_rows.append(nr)

    before = diversity_stats(_pairs(rows))
    after = diversity_stats([(v.instruction, v.format, v.answers) for v in all_vars])
    by_source_div = {}
    for s in sorted(per):
        src_rows = [r for r in rows if r["source"] == s]
        src_vars = [v for v in all_vars if v.meta.get("source") == s]
        b, a = diversity_stats(_pairs(src_rows)), diversity_stats([(v.instruction, v.format, v.answers) for v in src_vars])
        by_source_div[s] = {"templates_before": b.get("distinct_instruction_templates"),
                            "templates_after": a.get("distinct_instruction_templates"),
                            "tail_clause_entropy_before": b.get("tail_clause_entropy_bits"),
                            "tail_clause_entropy_after": a.get("tail_clause_entropy_bits"),
                            "formats_after": a.get("format_distribution")}
    stats = {
        "config": str(Path(args.config).relative_to(ROOT)) if Path(args.config).is_relative_to(ROOT) else args.config,
        "n_rows": len(rows),
        "per_source": {s: dict(per[s]) for s in sorted(per)},
        "tiers": {s: dict(tiers[s]) for s in sorted(tiers)},
        "rejected": {s: dict(rejected[s]) for s in sorted(rejected)},
        "diversity_before": before,
        "diversity_after": after,
        "diversity_by_source": by_source_div,
    }
    Path(args.stats).parent.mkdir(parents=True, exist_ok=True)
    Path(args.stats).write_text(json.dumps(stats, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    Path(args.preview).write_text(_preview(by_src, var_by_id), encoding="utf-8")

    tot = Counter()
    for c in per.values():
        tot.update(c)
    print(f"rows={tot['rows']} qas {tot['qas_before']}->{tot['qas_after']} "
          f"reasoning {tot['reasoning_before']}->{tot['reasoning_after']} "
          f"repaired={tot['answers_repaired']} derived={tot['derived_qas']} variants={tot['variants']}")
    print(f"templates {before['distinct_instruction_templates']}->{after['distinct_instruction_templates']}  "
          f"format entropy {before['format_entropy_bits']}->{after['format_entropy_bits']} bits")
    print(f"-> {out_dir}/rows.jsonl, variants.jsonl; {args.stats}; {args.preview}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
